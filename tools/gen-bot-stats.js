// Turns the old Telegram bot's database (deliveries table) into ui/bot_stats.js: only counts per strategy / market / timeframe /
// expiry / source – no user ids, no settings, no prices. Usage: node tools/gen-bot-stats.js <path to bot.db>
const fs = require('fs'), path = require('path');
const { DatabaseSync } = require('node:sqlite');
const db = new DatabaseSync(process.argv[2], { readOnly: true });
const rows = db.prepare("select strategy, market, tf, expiry_sec, src, result, entry_ts from deliveries where result in ('WIN','LOSS','DRAW')").all();
const SRC = { 'BinoDex OTC': 'bino', 'OANDA': 'oanda', 'OANDA live': 'oanda', 'Pocket Option OTC live': 'po', 'Pocket Option live': 'po' };
const g = {};
for (const r of rows) {
  const k = [r.strategy || '', r.market, r.tf, r.expiry_sec, SRC[r.src] || ''].join('|');
  const a = (g[k] ||= { s: r.strategy || '', m: r.market, tf: r.tf, e: r.expiry_sec, src: SRC[r.src] || '', n: 0, w: 0, l: 0 });
  a.n++; if (r.result === 'WIN') a.w++; if (r.result === 'LOSS') a.l++;
}
const ts = rows.map(r => r.entry_ts);
const out = { from: Math.min(...ts), to: Math.max(...ts), rows: Object.values(g) };
fs.writeFileSync(path.join(__dirname, '..', 'ui', 'bot_stats.js'),
  '// Generated by tools/gen-bot-stats.js from the old Telegram bot (counts only, no personal data).\nwindow.BOT_STATS = ' + JSON.stringify(out) + ';\n');
console.log('groups', out.rows.length, 'signals', rows.length);
