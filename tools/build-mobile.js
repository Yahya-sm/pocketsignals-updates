// Bundles the signal engine + UI into android/app/src/main/assets/www for the Android app.
// The engine modules run unchanged in the WebView; fs/path/events/ws are replaced by small browser shims.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'android', 'app', 'src', 'main', 'assets', 'www');
// Every file in src/ that another one require()s must be listed here (order: dependencies first).
const MODULES = ['po-client', 'indicators', 'levels', 'five_bot', 'bot_ports', 'strategies', 'assets', 'engine', 'po-switch'];

// Start settings for a new installation (strategies, pairs – no secrets); same on the PC and on GitHub's build servers.
const settings = fs.readFileSync(path.join(ROOT, 'defaults', 'settings.json'), 'utf8');
// No PocketOption session is built in: each phone uses the login from its own PocketOption tab.
// That keeps the APK free of secrets, so it can be published for online updates.
const ssidLine = '';

const shims = `
const __defaults = { 'signal-app-einstellungen.json': ${JSON.stringify(settings)}, 'signal-zugang.txt': ${JSON.stringify(ssidLine)} };
const __base = p => String(p).split(/[\\\\/]/).pop();
__mods.fs = {
  readFileSync(p) {
    const k = __base(p), v = localStorage.getItem('file:' + k);
    if (v !== null) return v;
    if (k in __defaults) return __defaults[k];
    throw new Error('ENOENT ' + k);
  },
  writeFileSync(p, d) { try { localStorage.setItem('file:' + __base(p), d); } catch (e) {} },
  mkdirSync() {}, existsSync(p) { return localStorage.getItem('file:' + __base(p)) !== null; },
};
__mods.path = { join: (...a) => a.join('/') };
// Node globals that shared modules may touch; they do not exist in the phone's WebView.
const process = { env: {} };
class EventEmitter {
  constructor() { this._ev = {}; }
  on(e, f) { (this._ev[e] ||= []).push(f); return this; }
  once(e, f) { const w = (...a) => { this.off(e, w); f(...a); }; return this.on(e, w); }
  off(e, f) { this._ev[e] = (this._ev[e] || []).filter(x => x !== f); return this; }
  removeListener(e, f) { return this.off(e, f); }
  emit(e, ...a) { (this._ev[e] || []).slice().forEach(f => f(...a)); return true; }
}
__mods.events = EventEmitter;
// Node 'ws'-style socket. In the Android app it runs over the native PoSocket (which sends the
// Origin header PocketOption requires); elsewhere it falls back to the browser WebSocket.
const __socks = {}; let __sockId = 0;
window.__wsEvent = (id, type, data) => {
  const w = __socks[id]; if (!w) return;
  if (type === 'open') { w._state = 1; w.emit('open'); }
  else if (type === 'close') { w._state = 3; delete __socks[id]; if (data && data !== 'closed') w.emit('error', new Error(data)); w.emit('close', 1000, data || ''); }
  else w.emit('message', { toString: () => data }, type === 'binary');
};
class WS extends EventEmitter {
  constructor(url) {
    super();
    if (window.AndroidApp && window.AndroidApp.wsOpen) {
      this.id = ++__sockId; this._state = 0; __socks[this.id] = this;
      window.AndroidApp.wsOpen(this.id, url);
      return;
    }
    const s = this.sock = new WebSocket(url); s.binaryType = 'arraybuffer';
    const dec = new TextDecoder();
    s.onopen = () => this.emit('open');
    s.onmessage = m => { const bin = typeof m.data !== 'string'; const t = bin ? dec.decode(m.data) : m.data; this.emit('message', { toString: () => t }, bin); };
    s.onclose = () => this.emit('close', 1000, '');
    s.onerror = () => this.emit('error', new Error('WebSocket-Fehler'));
  }
  get readyState() { return this.sock ? this.sock.readyState : this._state; }
  send(d) { if (this.sock) this.sock.send(d); else window.AndroidApp.wsSend(this.id, d); }
  close() { if (this.sock) this.sock.close(); else window.AndroidApp.wsClose(this.id); }
}
__mods.ws = WS;
`;

let bundle = `// Generated by tools/build-mobile.js – do not edit.\n(function () {\nconst __mods = {}, __defs = {};\n`;
bundle += `const require = n => { const k = n.replace(/^\\.\\//, ''); if (k in __mods) return __mods[k]; const m = { exports: {} }; __mods[k] = m.exports; __defs[k](m, m.exports); __mods[k] = m.exports; return m.exports; };\n`;
bundle += shims;
for (const m of MODULES) {
  const src = fs.readFileSync(path.join(ROOT, 'src', m + '.js'), 'utf8');
  bundle += `__defs[${JSON.stringify(m)}] = function (module, exports) {\nconst __dirname = '/app/src';\n${src}\n};\n`;
}
// GitHub repo for the phone's online updates.
bundle += `window.UPDATE_REPO = ${JSON.stringify(JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).updateRepo || '')};\n`;
bundle += fs.readFileSync(path.join(__dirname, 'mobile-local.js'), 'utf8');
bundle += `\n})();\n`;

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'engine.bundle.js'), bundle);
for (const f of ['i18n.js', 'app.js', 'style.css', 'icon.png', 'manifest.json']) fs.copyFileSync(path.join(ROOT, 'ui', f), path.join(OUT, f));
const html = fs.readFileSync(path.join(ROOT, 'ui', 'index.html'), 'utf8').replace('<script src="app.js"></script>', '<script src="engine.bundle.js"></script>\n<script src="app.js"></script>');
fs.writeFileSync(path.join(OUT, 'index.html'), html);
console.log('mobile bundle written:', OUT, Math.round(bundle.length / 1024) + ' KB');
